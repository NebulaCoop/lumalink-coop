//! LumaScript: a mod's logic as text, compiled to the `.lumascript` file the game runs on every platform (no native
//! code). The game's loader and evaluator are Nebula's `LumaScript.cpp`; the file layout and the opcodes here match
//! its `LumaScript.hpp` (a test reads the copy in the SDK). docs/reference/lumascript.md describes the language.
//!
//! ```text
//! var speed: float            // each object's own
//! global hits: int            // the mod's, shared by its objects
//! saved best: int             // kept in the save
//!
//! on start { speed = 2.5 }
//! on frame {
//!     let player = MR::getPlayerPos()
//!     if MR::isNear(self, player, 800.0) { goto chase }
//! }
//! state chase {
//!     on enter { MR::startBck(self, "Run", "") }
//!     on frame { wait 30; emit "roar" speed }
//! }
//! fn twice(x) { return x * 2 }
//! ```

use std::collections::HashMap;
use std::fmt::Write as _;

/// The toolkit the game offers, from the SDK's `toolkit.tsv` (generated by Nebula's tools/lumacore).
pub struct Toolkit {
    rows: HashMap<String, (String, String)>,
    // Overloaded names: the plain name to its rows ("MR::isBindedGround" -> ["MR::isBindedGround:h", ...]).
    overloads: HashMap<String, Vec<String>>,
}

impl Toolkit {
    pub fn parse(tsv: &str) -> Toolkit {
        let mut rows = HashMap::new();
        let mut overloads: HashMap<String, Vec<String>> = HashMap::new();
        for line in tsv.lines() {
            let mut cols = line.split('\t');
            let (Some(name), Some(params)) = (cols.next(), cols.next()) else { continue };
            let result = cols.next().unwrap_or("").to_string();
            if let Some(i) = name.rfind(':') {
                if i > 0 && name.as_bytes()[i - 1] != b':' {
                    overloads.entry(name[..i].to_string()).or_default().push(name.to_string());
                }
            }
            rows.insert(name.to_string(), (params.to_string(), result));
        }
        Toolkit { rows, overloads }
    }

    /// The SDK's toolkit (this LumaLink's Nebula).
    pub fn bundled() -> Toolkit {
        Toolkit::parse(include_str!("../sdk/toolkit.tsv"))
    }

    pub fn len(&self) -> usize {
        self.rows.len()
    }

    pub fn is_empty(&self) -> bool {
        self.rows.is_empty()
    }
}

