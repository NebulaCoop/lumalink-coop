// Tokens

#[derive(Debug, Clone, PartialEq)]
enum Tok {
    Name(String),
    Int(i64),
    Float(f64),
    Text(String),
    Punct(&'static str),
    End,
}

struct Lexed {
    toks: Vec<(Tok, u32)>,
}

const PUNCTS: [&str; 26] = [
    "==", "!=", "<=", ">=", "&&", "||", "+", "-", "*", "/", "%", "<", ">", "=", "!", "(", ")", "{", "}", "[", "]", ",",
    ".", ":", ";", "@",
];

fn lex(source: &str) -> Result<Lexed, Problem> {
    let bytes = source.as_bytes();
    let mut toks = Vec::new();
    let mut i = 0usize;
    let mut line = 1u32;
    while i < bytes.len() {
        let c = bytes[i];
        if c == b'\n' {
            line += 1;
            i += 1;
            continue;
        }
        if c.is_ascii_whitespace() {
            i += 1;
            continue;
        }
        if c == b'/' && bytes.get(i + 1) == Some(&b'/') {
            while i < bytes.len() && bytes[i] != b'\n' {
                i += 1;
            }
            continue;
        }
        if c == b'/' && bytes.get(i + 1) == Some(&b'*') {
            let start = line;
            i += 2;
            loop {
                if i + 1 >= bytes.len() {
                    return Err(Problem { line: start, text: "a comment that never ends (*/)".into() });
                }
                if bytes[i] == b'\n' {
                    line += 1;
                }
                if bytes[i] == b'*' && bytes[i + 1] == b'/' {
                    i += 2;
                    break;
                }
                i += 1;
            }
            continue;
        }
        if c.is_ascii_alphabetic() || c == b'_' {
            let start = i;
            loop {
                while i < bytes.len() && (bytes[i].is_ascii_alphanumeric() || bytes[i] == b'_') {
                    i += 1;
                }
                // Qualified names: MR::startBck, AreaObj::isInVolume.
                if i + 2 < bytes.len() && bytes[i] == b':' && bytes[i + 1] == b':' && (bytes[i + 2].is_ascii_alphabetic() || bytes[i + 2] == b'_') {
                    i += 2;
                    continue;
                }
                break;
            }
            toks.push((Tok::Name(source[start..i].to_string()), line));
            continue;
        }
        if c.is_ascii_digit() {
            let start = i;
            while i < bytes.len() && bytes[i].is_ascii_digit() {
                i += 1;
            }
            let mut float = false;
            if i + 1 < bytes.len() && bytes[i] == b'.' && bytes[i + 1].is_ascii_digit() {
                float = true;
                i += 1;
                while i < bytes.len() && bytes[i].is_ascii_digit() {
                    i += 1;
                }
            }
            if i < bytes.len() && (bytes[i] == b'e' || bytes[i] == b'E') {
                let mut j = i + 1;
                if j < bytes.len() && (bytes[j] == b'+' || bytes[j] == b'-') {
                    j += 1;
                }
                if j < bytes.len() && bytes[j].is_ascii_digit() {
                    float = true;
                    i = j;
                    while i < bytes.len() && bytes[i].is_ascii_digit() {
                        i += 1;
                    }
                }
            }
            let text = &source[start..i];
            if float {
                let v: f64 = text.parse().map_err(|_| Problem { line, text: format!("{text} is not a number") })?;
                toks.push((Tok::Float(v), line));
            } else {
                let v: i64 = text.parse().map_err(|_| Problem { line, text: format!("{text} is too large a whole number") })?;
                toks.push((Tok::Int(v), line));
            }
            continue;
        }
        if c == b'"' {
            let start = line;
            i += 1;
            let mut out = String::new();
            loop {
                let Some(&d) = bytes.get(i) else {
                    return Err(Problem { line: start, text: "text that never ends (\")".into() });
                };
                if d == b'\n' {
                    return Err(Problem { line: start, text: "text that runs past its line (a \" is missing)".into() });
                }
                if d == b'"' {
                    i += 1;
                    break;
                }
                if d == b'\\' {
                    let e = bytes.get(i + 1).copied().unwrap_or(b' ');
                    out.push(match e {
                        b'n' => '\n',
                        b't' => '\t',
                        b'"' => '"',
                        b'\\' => '\\',
                        _ => return Err(Problem { line, text: format!("\\{} is not an escape (\\n, \\t, \\\", \\\\)", e as char) }),
                    });
                    i += 2;
                    continue;
                }
                // Whole UTF-8 characters.
                let ch = source[i..].chars().next().unwrap_or(' ');
                out.push(ch);
                i += ch.len_utf8();
            }
            toks.push((Tok::Text(out), line));
            continue;
        }
        let rest = &source[i..];
        if let Some(p) = PUNCTS.iter().find(|p| rest.starts_with(**p)) {
            toks.push((Tok::Punct(p), line));
            i += p.len();
            continue;
        }
        let ch = rest.chars().next().unwrap_or('?');
        return Err(Problem { line, text: format!("'{ch}' is not part of LumaScript") });
    }
    toks.push((Tok::End, line));
    Ok(Lexed { toks })
}

// ---------------------------------------------------------------------------------------------------------------------
// Syntax

#[derive(Debug, Clone)]
enum Expr {
    Int(i64),
    Float(f64),
    Text(String),
    Bool(bool),
    None,
    Name(String),
    Unary(&'static str, Box<Expr>),
    Binary(&'static str, Box<Expr>, Box<Expr>),
    Call(String, Vec<Expr>),
    Field(Box<Expr>, String, Option<Box<Expr>>),
}

#[derive(Debug, Clone)]
enum Stmt {
    Let(Vec<String>, Expr, u32),
    Assign(String, Expr, u32),
    FieldSet(Expr, String, Expr, u32),
    If(Expr, Vec<Stmt>, Vec<Stmt>, u32),
    While(Expr, Vec<Stmt>, u32),
    Return(Option<Expr>, u32),
    Wait(Expr, u32),
    Goto(String, u32),
    Emit(String, Option<Expr>, u32),
    Expr(Expr, u32),
    Break(u32),
}

#[derive(Debug, Clone, Copy, PartialEq)]
enum VarKind {
    Local,
    Global,
    Saved,
}

struct VarDecl {
    name: String,
    kind: VarKind,
    value_kind: u8,
    init: Option<Expr>,
    line: u32,
}

struct HandlerDecl {
    event: String,
    state: Option<String>,
    params: Vec<String>,
    body: Vec<Stmt>,
    line: u32,
}

struct FnDecl {
    name: String,
    params: Vec<String>,
    body: Vec<Stmt>,
    line: u32,
}

struct Parser {
    toks: Vec<(Tok, u32)>,
    at: usize,
}

type P<T> = Result<T, Problem>;

impl Parser {
    fn peek(&self) -> &Tok {
        &self.toks[self.at].0
    }
    fn line(&self) -> u32 {
        self.toks[self.at].1
    }
    fn next(&mut self) -> Tok {
        let t = self.toks[self.at].0.clone();
        if self.at + 1 < self.toks.len() {
            self.at += 1;
        }
        t
    }
    fn is(&self, p: &str) -> bool {
        matches!(self.peek(), Tok::Punct(q) if *q == p)
    }
    fn is_word(&self, w: &str) -> bool {
        matches!(self.peek(), Tok::Name(n) if n == w)
    }
    fn eat(&mut self, p: &str) -> bool {
        if self.is(p) {
            self.next();
            true
        } else {
            false
        }
    }
    fn expect(&mut self, p: &str) -> P<()> {
        if self.eat(p) {
            Ok(())
        } else {
            Err(self.problem(&format!("'{p}' expected here")))
        }
    }
    fn problem(&self, text: &str) -> Problem {
        let found = match self.peek() {
            Tok::Name(n) => format!(" (found {n})"),
            Tok::Int(v) => format!(" (found {v})"),
            Tok::Float(v) => format!(" (found {v})"),
            Tok::Text(t) => format!(" (found \"{t}\")"),
            Tok::Punct(p) => format!(" (found '{p}')"),
            Tok::End => " (found the end of the file)".into(),
        };
        Problem { line: self.line(), text: format!("{text}{found}") }
    }
    fn name(&mut self, what: &str) -> P<String> {
        match self.peek().clone() {
            Tok::Name(n) if !is_keyword(&n) => {
                self.next();
                Ok(n)
            }
            _ => Err(self.problem(&format!("{what} expected"))),
        }
    }

    fn file(&mut self) -> P<(Vec<VarDecl>, Vec<HandlerDecl>, Vec<FnDecl>)> {
        let mut vars = Vec::new();
        let mut handlers = Vec::new();
        let mut fns = Vec::new();
        loop {
            while self.eat(";") {}
            let line = self.line();
            match self.peek().clone() {
                Tok::End => break,
                Tok::Name(w) if w == "var" || w == "global" || w == "saved" => {
                    self.next();
                    let kind = match w.as_str() {
                        "var" => VarKind::Local,
                        "global" => VarKind::Global,
                        _ => VarKind::Saved,
                    };
                    let name = self.name("a variable's name")?;
                    let mut value_kind = KIND_NONE;
                    if self.eat(":") {
                        let t = self.name("a kind (int, float, bool, text, vec3)")?;
                        value_kind = match t.as_str() {
                            "int" => KIND_INT,
                            "float" => KIND_FLOAT,
                            "bool" => KIND_BOOL,
                            "text" => KIND_TEXT,
                            "vec3" => KIND_VEC3,
                            "any" => KIND_NONE,
                            _ => return Err(Problem { line, text: format!("{t} is not a kind (int, float, bool, text, vec3, any)") }),
                        };
                    }
                    let init = if self.eat("=") { Some(self.expr()?) } else { None };
                    if kind == VarKind::Saved && value_kind == KIND_NONE {
                        return Err(Problem { line, text: format!("saved {name} needs its kind (saved {name}: int)") });
                    }
                    if kind != VarKind::Local && init.is_some() {
                        return Err(Problem { line, text: format!("{name}: only a var takes a starting value here; a {w} starts at its kind's zero") });
                    }
                    let value_kind = if value_kind == KIND_NONE { init.as_ref().map_or(KIND_NONE, literal_kind) } else { value_kind };
                    vars.push(VarDecl { name, kind, value_kind, init, line });
                }
                Tok::Name(w) if w == "fn" => {
                    self.next();
                    let name = self.name("a function's name")?;
                    let params = self.params()?;
                    let body = self.block()?;
                    fns.push(FnDecl { name, params, body, line });
                }
                Tok::Name(w) if w == "on" => handlers.push(self.handler(None)?),
                Tok::Name(w) if w == "state" => {
                    self.next();
                    let state = self.name("a state's name")?;
                    self.expect("{")?;
                    while !self.eat("}") {
                        while self.eat(";") {}
                        if self.eat("}") {
                            break;
                        }
                        if !self.is_word("on") {
                            return Err(self.problem("a state holds only 'on' handlers"));
                        }
                        handlers.push(self.handler(Some(state.clone()))?);
                    }
                }
                _ => return Err(self.problem("var, global, saved, fn, on or state expected")),
            }
        }
        Ok((vars, handlers, fns))
    }

    fn handler(&mut self, state: Option<String>) -> P<HandlerDecl> {
        let line = self.line();
        self.next(); // on
        let mut event = match self.next() {
            Tok::Name(n) => n,
            Tok::Text(t) => t,
            _ => return Err(Problem { line, text: "an event's name expected after 'on'".into() }),
        };
        // on event boom / on message ACTMES_X / on message 41: "event:boom", "message:ACTMES_X", "message:41".
        if (event == "event" || event == "message") && matches!(self.peek(), Tok::Name(_) | Tok::Text(_) | Tok::Int(_)) {
            let rest = match self.next() {
                Tok::Name(n) | Tok::Text(n) => n,
                Tok::Int(v) => v.to_string(),
                _ => unreachable!(),
            };
            event = format!("{event}:{rest}");
        }
        let params = if self.is("(") { self.params()? } else { Vec::new() };
        let body = self.block()?;
        Ok(HandlerDecl { event, state, params, body, line })
    }

    fn params(&mut self) -> P<Vec<String>> {
        self.expect("(")?;
        let mut out = Vec::new();
        if self.eat(")") {
            return Ok(out);
        }
        loop {
            out.push(self.name("a parameter's name")?);
            if self.eat(")") {
                return Ok(out);
            }
            self.expect(",")?;
        }
    }

    fn block(&mut self) -> P<Vec<Stmt>> {
        self.expect("{")?;
        let mut out = Vec::new();
        loop {
            while self.eat(";") {}
            if self.eat("}") {
                return Ok(out);
            }
            if matches!(self.peek(), Tok::End) {
                return Err(self.problem("'}' expected"));
            }
            out.push(self.stmt()?);
        }
    }

    fn stmt(&mut self) -> P<Stmt> {
        let line = self.line();
        if let Tok::Name(w) = self.peek().clone() {
            match w.as_str() {
                "let" => {
                    self.next();
                    let mut names = vec![self.name("a name")?];
                    while self.eat(",") {
                        names.push(self.name("a name")?);
                    }
                    self.expect("=")?;
                    return Ok(Stmt::Let(names, self.expr()?, line));
                }
                "if" => return self.if_stmt(),
                "while" => {
                    self.next();
                    let cond = self.expr()?;
                    let body = self.block()?;
                    return Ok(Stmt::While(cond, body, line));
                }
                "break" => {
                    self.next();
                    return Ok(Stmt::Break(line));
                }
                "return" => {
                    self.next();
                    let value = if self.is("}") || self.is(";") || self.line() != line { None } else { Some(self.expr()?) };
                    return Ok(Stmt::Return(value, line));
                }
                "wait" => {
                    self.next();
                    return Ok(Stmt::Wait(self.expr()?, line));
                }
                "goto" => {
                    self.next();
                    return Ok(Stmt::Goto(self.name("a state's name")?, line));
                }
                "emit" => {
                    self.next();
                    let event = match self.next() {
                        Tok::Name(n) | Tok::Text(n) => n,
                        _ => return Err(Problem { line, text: "an event's name expected after 'emit'".into() }),
                    };
                    let value = if self.is("}") || self.is(";") || self.line() != line { None } else { Some(self.expr()?) };
                    return Ok(Stmt::Emit(event, value, line));
                }
                _ => {}
            }
        }
        let e = self.expr()?;
        if self.eat("=") {
            let value = self.expr()?;
            return match e {
                Expr::Name(n) => Ok(Stmt::Assign(n, value, line)),
                Expr::Field(obj, field, None) if !matches!(field.as_str(), "x" | "y" | "z") => Ok(Stmt::FieldSet(*obj, field, value, line)),
                _ => Err(Problem { line, text: "only a variable or an object's field can be set".into() }),
            };
        }
        if !matches!(e, Expr::Call(..)) {
            return Err(Problem { line, text: "a value that is not used: set it, or call something".into() });
        }
        Ok(Stmt::Expr(e, line))
    }

    fn if_stmt(&mut self) -> P<Stmt> {
        let line = self.line();
        self.next(); // if
        let cond = self.expr()?;
        let then = self.block()?;
        let otherwise = if self.is_word("else") {
            self.next();
            if self.is_word("if") {
                vec![self.if_stmt()?]
            } else {
                self.block()?
            }
        } else {
            Vec::new()
        };
        Ok(Stmt::If(cond, then, otherwise, line))
    }

    fn expr(&mut self) -> P<Expr> {
        self.binary(0)
    }

    fn binary(&mut self, level: usize) -> P<Expr> {
        const LEVELS: [&[&str]; 6] = [&["||", "or"], &["&&", "and"], &["==", "!="], &["<", "<=", ">", ">="], &["+", "-"], &["*", "/", "%"]];
        if level == LEVELS.len() {
            return self.unary();
        }
        let mut left = self.binary(level + 1)?;
        loop {
            let found = LEVELS[level].iter().find(|p| self.is(p) || self.is_word(p)).copied();
            let Some(p) = found else { break };
            self.next();
            let right = self.binary(level + 1)?;
            let p: &'static str = match p {
                "or" => "||",
                "and" => "&&",
                other => other,
            };
            left = Expr::Binary(p, Box::new(left), Box::new(right));
        }
        Ok(left)
    }

    fn unary(&mut self) -> P<Expr> {
        if self.eat("-") {
            let e = self.unary()?;
            return Ok(match e {
                Expr::Int(v) => Expr::Int(v.wrapping_neg()),
                Expr::Float(v) => Expr::Float(-v),
                e => Expr::Unary("-", Box::new(e)),
            });
        }
        if self.eat("!") || (self.is_word("not") && {
            self.next();
            true
        }) {
            return Ok(Expr::Unary("!", Box::new(self.unary()?)));
        }
        self.postfix()
    }

    fn postfix(&mut self) -> P<Expr> {
        let mut e = self.primary()?;
        loop {
            if self.eat(".") {
                let field = self.name("a field's name")?;
                let index = if self.eat("[") {
                    let i = self.expr()?;
                    self.expect("]")?;
                    Some(Box::new(i))
                } else {
                    None
                };
                // A member's own field, one level down (self.mFlag.mIsDead): one name, as the game lists it.
                let xyz = |f: &str| matches!(f, "x" | "y" | "z");
                e = match e {
                    Expr::Field(obj, outer, None) if !xyz(&field) && !xyz(&outer) && !outer.contains('.') => {
                        Expr::Field(obj, format!("{outer}.{field}"), index)
                    }
                    e => Expr::Field(Box::new(e), field, index),
                };
                continue;
            }
            break;
        }
        Ok(e)
    }

    fn primary(&mut self) -> P<Expr> {
        let line = self.line();
        match self.next() {
            Tok::Int(v) => Ok(Expr::Int(v)),
            Tok::Float(v) => Ok(Expr::Float(v)),
            Tok::Text(t) => Ok(Expr::Text(t)),
            Tok::Punct("(") => {
                let e = self.expr()?;
                self.expect(")")?;
                Ok(e)
            }
            Tok::Name(n) => match n.as_str() {
                "true" => Ok(Expr::Bool(true)),
                "false" => Ok(Expr::Bool(false)),
                "none" => Ok(Expr::None),
                _ if is_keyword(&n) => Err(Problem { line, text: format!("{n} can't start a value") }),
                _ => {
                    let mut name = n;
                    // An overload by its value letters: MR::isBindedGround:hh(...).
                    if name.contains("::") && self.is(":") {
                        if let Tok::Name(letters) = &self.toks[self.at + 1].0 {
                            if letters.bytes().all(|b| b.is_ascii_alphabetic()) && matches!(self.toks.get(self.at + 2), Some((Tok::Punct("("), _))) {
                                let letters = letters.clone();
                                self.next();
                                self.next();
                                name = format!("{name}:{letters}");
                            }
                        }
                    }
                    // The plugin API: nebula.<call>, and NebulaCoop's multiplayer calls as coop.<call>.
                    if (name == "nebula" || name == "coop") && self.is(".") {
                        self.next();
                        let call = self.name("a Nebula call's name")?;
                        name = format!("{name}.{call}");
                    }
                    if self.eat("(") {
                        let mut args = Vec::new();
                        if !self.eat(")") {
                            loop {
                                args.push(self.expr()?);
                                if self.eat(")") {
                                    break;
                                }
                                self.expect(",")?;
                            }
                        }
                        Ok(Expr::Call(name, args))
                    } else {
                        Ok(Expr::Name(name))
                    }
                }
            },
            Tok::End => Err(Problem { line, text: "a value expected before the end of the file".into() }),
            other => Err(Problem { line, text: format!("a value expected (found {other:?})") }),
        }
    }
}

/// A row of the plugin API (called through the host's table): nebula.<name>, or NebulaCoop's coop.<name>.
fn is_api(row: &str) -> bool {
    row.starts_with("nebula.") || row.starts_with("coop.")
}

fn is_keyword(n: &str) -> bool {
    matches!(
        n,
        "var" | "global" | "saved" | "fn" | "on" | "state" | "let" | "if" | "else" | "while" | "break" | "return" | "wait" | "goto"
            | "emit" | "and" | "or" | "not"
    )
}

fn literal_kind(e: &Expr) -> u8 {
    match e {
        Expr::Int(_) => KIND_INT,
        Expr::Float(_) => KIND_FLOAT,
        Expr::Bool(_) => KIND_BOOL,
        Expr::Text(_) => KIND_TEXT,
        Expr::Call(n, _) if n == "vec" => KIND_VEC3,
        _ => KIND_NONE,
    }
}

