#[derive(Clone, Copy)]
struct Step {
    op: u8,
    dst: u8,
    a: u8,
    b: u8,
    imm: u16,
    imm2: u16,
}

#[derive(Clone, PartialEq)]
enum Constant {
    None,
    Bool(bool),
    Int(i64),
    Float(u64),
    Vec3([u32; 3]),
    Text(u32),
}

struct Function {
    name: u32,
    first: u32,
    count: u32,
    registers: u16,
    params: u16,
    line: u32,
}

#[derive(Default)]
struct Out {
    strings: Vec<String>,
    string_index: HashMap<String, u32>,
    constants: Vec<Constant>,
    imports: Vec<(u8, u32, u32)>,
    import_index: HashMap<(u8, u32), u16>,
    functions: Vec<Function>,
    steps: Vec<Step>,
    handlers: Vec<(u32, u32, u32)>,
    locals: Vec<(u32, u8)>,
    globals: Vec<(u32, u8)>,
    saved: Vec<(u32, u8)>,
}

impl Out {
    fn string(&mut self, s: &str) -> u32 {
        if let Some(&i) = self.string_index.get(s) {
            return i;
        }
        let i = self.strings.len() as u32;
        self.strings.push(s.to_string());
        self.string_index.insert(s.to_string(), i);
        i
    }
    fn constant(&mut self, c: Constant, line: u32) -> P<u16> {
        if let Some(i) = self.constants.iter().position(|x| *x == c) {
            return Ok(i as u16);
        }
        if self.constants.len() >= u16::MAX as usize {
            return Err(Problem { line, text: "more than 65535 different values in one script".into() });
        }
        self.constants.push(c);
        Ok((self.constants.len() - 1) as u16)
    }
    fn import(&mut self, kind: u8, name: &str, line: u32) -> P<u16> {
        let s = self.string(name);
        if let Some(&i) = self.import_index.get(&(kind, s)) {
            return Ok(i);
        }
        if self.imports.len() >= u16::MAX as usize {
            return Err(Problem { line, text: "more than 65535 different names in one script".into() });
        }
        self.imports.push((kind, s, line));
        let i = (self.imports.len() - 1) as u16;
        self.import_index.insert((kind, s), i);
        Ok(i)
    }
}

struct Scope {
    names: Vec<(String, u8)>,
}

struct FnCtx<'a> {
    out: &'a mut Out,
    toolkit: &'a Toolkit,
    vars: &'a HashMap<String, (VarKind, u16)>,
    fns: &'a HashMap<String, (u32, usize)>,
    states: &'a [String],
    steps: Vec<Step>,
    scopes: Vec<Scope>,
    next: usize,
    max: usize,
    is_handler: bool,
    loops: Vec<Vec<usize>>,
    name: String,
}

impl FnCtx<'_> {
    fn emit(&mut self, op: u8, dst: u8, a: u8, b: u8, imm: u16, imm2: u16) -> usize {
        self.steps.push(Step { op, dst, a, b, imm, imm2 });
        self.steps.len() - 1
    }
    fn temp(&mut self, line: u32) -> P<u8> {
        self.temps(1, line)
    }
    fn temps(&mut self, n: usize, line: u32) -> P<u8> {
        if self.next + n > MAX_REGISTERS {
            return Err(Problem { line, text: format!("{}: too many values at once (at most {MAX_REGISTERS})", self.name) });
        }
        let r = self.next as u8;
        self.next += n;
        self.max = self.max.max(self.next);
        Ok(r)
    }
    fn lookup(&self, name: &str) -> Option<u8> {
        self.scopes.iter().rev().flat_map(|s| s.names.iter().rev()).find(|(n, _)| n == name).map(|(_, r)| *r)
    }
    fn declare(&mut self, name: &str, line: u32) -> P<u8> {
        let r = self.temp(line)?;
        self.scopes.last_mut().expect("a scope").names.push((name.to_string(), r));
        Ok(r)
    }
    fn patch(&mut self, at: usize, target: usize) {
        self.steps[at].imm = target as u16;
    }

    fn block(&mut self, body: &[Stmt]) -> P<()> {
        let saved = self.next;
        self.scopes.push(Scope { names: Vec::new() });
        for s in body {
            self.stmt(s)?;
        }
        self.scopes.pop();
        self.next = saved;
        Ok(())
    }

    fn stmt(&mut self, s: &Stmt) -> P<()> {
        let temps = self.next;
        match s {
            Stmt::Let(names, value, line) => {
                if names.len() == 1 {
                    let r = self.expr(value, None, *line)?;
                    self.next = temps;
                    let dst = self.declare(&names[0], *line)?;
                    if r != dst {
                        self.emit(op::MOVE, dst, r, 0, 0, 0);
                    }
                    return Ok(());
                }
                // let a, b = call(...): the call's result and the values it gives back.
                let Expr::Call(name, args) = value else {
                    return Err(Problem { line: *line, text: "several names take a call's results".into() });
                };
                let base = self.next;
                let first = self.call(name, args, Some(names.len()), *line)?;
                self.next = base;
                let mut regs = Vec::new();
                for n in names {
                    regs.push(self.declare(n, *line)?);
                }
                for (k, r) in regs.iter().enumerate() {
                    if *r != first + k as u8 {
                        self.emit(op::MOVE, *r, first + k as u8, 0, 0, 0);
                    }
                }
            }
            Stmt::Assign(name, value, line) => {
                if let Some(dst) = self.lookup(name) {
                    let r = self.expr(value, Some(dst), *line)?;
                    if r != dst {
                        self.emit(op::MOVE, dst, r, 0, 0, 0);
                    }
                } else if let Some(&(kind, index)) = self.vars.get(name) {
                    let r = self.expr(value, None, *line)?;
                    let o = match kind {
                        VarKind::Local => op::SET_LOCAL,
                        VarKind::Global => op::SET_GLOBAL,
                        VarKind::Saved => op::SET_SAVED,
                    };
                    self.emit(o, 0, r, 0, index, 0);
                } else if name == "self" {
                    return Err(Problem { line: *line, text: "self can't be set".into() });
                } else {
                    return Err(Problem { line: *line, text: format!("{name} is not a variable here (let {name} = ... makes one)") });
                }
            }
            Stmt::FieldSet(obj, field, value, line) => {
                let o = self.expr(obj, None, *line)?;
                let v = self.expr(value, None, *line)?;
                let imp = self.out.import(IMPORT_FIELD, field, *line)?;
                self.emit(op::FIELD_SET, 0, o, v, imp, 0);
            }
            Stmt::If(cond, then, otherwise, line) => {
                let c = self.expr(cond, None, *line)?;
                self.next = temps;
                let jump_else = self.emit(op::JUMP_IF_NOT, 0, c, 0, 0, 0);
                self.block(then)?;
                if otherwise.is_empty() {
                    let end = self.steps.len();
                    self.patch(jump_else, end);
                } else {
                    let jump_end = self.emit(op::JUMP, 0, 0, 0, 0, 0);
                    let else_at = self.steps.len();
                    self.patch(jump_else, else_at);
                    self.block(otherwise)?;
                    let end = self.steps.len();
                    self.patch(jump_end, end);
                }
            }
            Stmt::While(cond, body, line) => {
                let top = self.steps.len();
                let c = self.expr(cond, None, *line)?;
                self.next = temps;
                let exit = self.emit(op::JUMP_IF_NOT, 0, c, 0, 0, 0);
                self.loops.push(Vec::new());
                self.block(body)?;
                self.emit(op::JUMP, 0, 0, 0, top as u16, 0);
                let end = self.steps.len();
                self.patch(exit, end);
                for b in self.loops.pop().unwrap_or_default() {
                    self.patch(b, end);
                }
            }
            Stmt::Break(line) => {
                if self.loops.is_empty() {
                    return Err(Problem { line: *line, text: "break outside a while".into() });
                }
                let at = self.emit(op::JUMP, 0, 0, 0, 0, 0);
                self.loops.last_mut().expect("a loop").push(at);
            }
            Stmt::Return(value, line) => match value {
                Some(v) => {
                    let r = self.expr(v, None, *line)?;
                    self.emit(op::RETURN, 0, r, 1, 0, 0);
                }
                None => {
                    self.emit(op::RETURN, 0, 0, 0, 0, 0);
                }
            },
            Stmt::Wait(frames, line) => {
                if !self.is_handler {
                    return Err(Problem { line: *line, text: format!("{}: only a handler (on ...) can wait, not a fn", self.name) });
                }
                let r = self.expr(frames, None, *line)?;
                self.emit(op::WAIT, 0, r, 0, 0, 0);
            }
            Stmt::Goto(state, line) => {
                if !self.states.iter().any(|s| s == state) {
                    return Err(Problem { line: *line, text: format!("there is no state {state}") });
                }
                let s = self.out.string(state);
                if s > u16::MAX as u32 {
                    return Err(Problem { line: *line, text: "too many names in one script".into() });
                }
                self.emit(op::SET_STATE, 0, 0, 0, s as u16, 0);
            }
            Stmt::Emit(event, value, line) => {
                let r = match value {
                    Some(v) => self.expr(v, None, *line)?,
                    None => self.expr(&Expr::None, None, *line)?,
                };
                let imp = self.out.import(IMPORT_EVENT, event, *line)?;
                self.emit(op::EMIT, 0, r, 0, imp, 0);
            }
            Stmt::Expr(e, line) => {
                if let Expr::Call(name, args) = e {
                    self.call(name, args, Some(0), *line)?;
                } else {
                    self.expr(e, None, *line)?;
                }
            }
        }
        self.next = temps;
        Ok(())
    }

    // Puts the value in a register: `want` when given (or the variable's own register when the value is one).
    fn expr(&mut self, e: &Expr, want: Option<u8>, line: u32) -> P<u8> {
        let dst = |ctx: &mut Self| -> P<u8> { want.map_or_else(|| ctx.temp(line), Ok) };
        Ok(match e {
            Expr::Int(v) => {
                let d = dst(self)?;
                let c = self.out.constant(Constant::Int(*v), line)?;
                self.emit(op::LOAD_CONST, d, 0, 0, c, 0);
                d
            }
            Expr::Float(v) => {
                let d = dst(self)?;
                let c = self.out.constant(Constant::Float(v.to_bits()), line)?;
                self.emit(op::LOAD_CONST, d, 0, 0, c, 0);
                d
            }
            Expr::Bool(v) => {
                let d = dst(self)?;
                let c = self.out.constant(Constant::Bool(*v), line)?;
                self.emit(op::LOAD_CONST, d, 0, 0, c, 0);
                d
            }
            Expr::None => {
                let d = dst(self)?;
                let c = self.out.constant(Constant::None, line)?;
                self.emit(op::LOAD_CONST, d, 0, 0, c, 0);
                d
            }
            Expr::Text(t) => {
                let d = dst(self)?;
                let s = self.out.string(t);
                let c = self.out.constant(Constant::Text(s), line)?;
                self.emit(op::LOAD_CONST, d, 0, 0, c, 0);
                d
            }
            Expr::Name(n) => {
                if let Some(r) = self.lookup(n) {
                    if let Some(w) = want {
                        if w != r {
                            self.emit(op::MOVE, w, r, 0, 0, 0);
                        }
                        return Ok(w);
                    }
                    return Ok(r);
                }
                if let Some(&(kind, index)) = self.vars.get(n) {
                    let d = dst(self)?;
                    let o = match kind {
                        VarKind::Local => op::GET_LOCAL,
                        VarKind::Global => op::GET_GLOBAL,
                        VarKind::Saved => op::GET_SAVED,
                    };
                    self.emit(o, d, 0, 0, index, 0);
                    return Ok(d);
                }
                if n == "self" {
                    return Err(Problem { line, text: format!("{}: self is a handler's (a fn takes it as a parameter)", self.name) });
                }
                return Err(Problem { line, text: format!("{n} is not known here") });
            }
            Expr::Unary(o, inner) => {
                let a = self.expr(inner, None, line)?;
                let d = dst(self)?;
                self.emit(if *o == "-" { op::NEG } else { op::NOT }, d, a, 0, 0, 0);
                d
            }
            Expr::Binary(o, l, r) if *o == "&&" || *o == "||" => {
                // Short: the right side runs only when the left doesn't decide; the value is the last one looked at.
                let d = dst(self)?;
                let saved = self.next;
                self.expr(l, Some(d), line)?;
                let jump = self.emit(if *o == "&&" { op::JUMP_IF_NOT } else { op::JUMP_IF }, 0, d, 0, 0, 0);
                self.expr(r, Some(d), line)?;
                let end = self.steps.len();
                self.patch(jump, end);
                self.next = saved;
                d
            }
            Expr::Binary(o, l, r) => {
                let a = self.expr(l, None, line)?;
                let b = self.expr(r, None, line)?;
                let d = dst(self)?;
                let code = match *o {
                    "+" => op::ADD,
                    "-" => op::SUB,
                    "*" => op::MUL,
                    "/" => op::DIV,
                    "%" => op::MOD,
                    "==" => op::EQ,
                    "!=" => op::NE,
                    "<" => op::LT,
                    "<=" => op::LE,
                    ">" => op::GT,
                    ">=" => op::GE,
                    _ => unreachable!(),
                };
                self.emit(code, d, a, b, 0, 0);
                d
            }
            Expr::Field(obj, field, index) => {
                let o = self.expr(obj, None, line)?;
                if index.is_none() && matches!(field.as_str(), "x" | "y" | "z") {
                    let d = dst(self)?;
                    let code = match field.as_str() {
                        "x" => op::VEC_X,
                        "y" => op::VEC_Y,
                        _ => op::VEC_Z,
                    };
                    self.emit(code, d, o, 0, 0, 0);
                    return Ok(d);
                }
                let b = match index {
                    Some(i) => self.expr(i, None, line)?,
                    None => 255,
                };
                let d = dst(self)?;
                let imp = self.out.import(IMPORT_FIELD, field, line)?;
                self.emit(op::FIELD_GET, d, o, b, imp, 0);
                d
            }
            Expr::Call(name, args) => {
                let r = self.call(name, args, None, line)?;
                if let Some(w) = want {
                    if w != r {
                        self.emit(op::MOVE, w, r, 0, 0, 0);
                    }
                    return Ok(w);
                }
                r
            }
        })
    }

    // Arguments into consecutive registers: the first one.
    fn args(&mut self, args: &[Expr], line: u32) -> P<u8> {
        let first = self.temps(args.len().max(1), line)?;
        for (k, a) in args.iter().enumerate() {
            self.expr(a, Some(first + k as u8), line)?;
        }
        Ok(first)
    }

    // A call: `results` None for a value (one register), Some(n) for n results (0: none kept). Returns the first.
    fn call(&mut self, name: &str, args: &[Expr], results: Option<usize>, line: u32) -> P<u8> {
        let want = results.unwrap_or(1);
        let simple = |ctx: &mut Self, code: u8, n: usize| -> P<u8> {
            if args.len() != n {
                return Err(Problem { line, text: format!("{name} takes {n} value{}", if n == 1 { "" } else { "s" }) });
            }
            let regs: Vec<u8> = args.iter().map(|a| ctx.expr(a, None, line)).collect::<P<_>>()?;
            let d = ctx.temp(line)?;
            match n {
                1 => ctx.emit(code, d, regs[0], 0, 0, 0),
                2 => ctx.emit(code, d, regs[0], regs[1], 0, 0),
                _ => ctx.emit(code, d, regs[0], regs[1], regs[2] as u16, 0),
            };
            Ok(d)
        };
        // vec of three numbers written out: one value in the file.
        if name == "vec" && args.len() == 3 {
            let lit: Vec<Option<f32>> = args
                .iter()
                .map(|a| match a {
                    Expr::Int(v) => Some(*v as f32),
                    Expr::Float(v) => Some(*v as f32),
                    _ => None,
                })
                .collect();
            if lit.iter().all(Option::is_some) {
                let v = [lit[0].unwrap_or(0.0).to_bits(), lit[1].unwrap_or(0.0).to_bits(), lit[2].unwrap_or(0.0).to_bits()];
                let c = self.out.constant(Constant::Vec3(v), line)?;
                let d = self.temp(line)?;
                self.emit(op::LOAD_CONST, d, 0, 0, c, 0);
                return Ok(d);
            }
        }
        match name {
            "vec" => return simple(self, op::MAKE_VEC3, 3),
            "lerp" => return simple(self, op::LERP, 3),
            "dot" => return simple(self, op::DOT, 2),
            "cross" => return simple(self, op::CROSS, 2),
            "length" => return simple(self, op::LENGTH, 1),
            "normalize" => return simple(self, op::NORMALIZE, 1),
            "min" => return simple(self, op::MIN, 2),
            "max" => return simple(self, op::MAX, 2),
            "abs" => return simple(self, op::ABS, 1),
            "floor" => return simple(self, op::FLOOR, 1),
            "sqrt" => return simple(self, op::SQRT, 1),
            "sin" => return simple(self, op::SIN, 1),
            "cos" => return simple(self, op::COS, 1),
            "atan2" => return simple(self, op::ATAN2, 2),
            "random" => return simple(self, op::RANDOM, 2),
            "int" => return simple(self, op::TO_INT, 1),
            "float" => return simple(self, op::TO_FLOAT, 1),
            "format" => {
                let Some(Expr::Text(f)) = args.first() else {
                    return Err(Problem { line, text: "format takes its text first: format(\"{} coins\", n)".into() });
                };
                let s = self.out.string(f);
                let c = self.out.constant(Constant::Text(s), line)?;
                let first = self.args(&args[1..], line)?;
                let d = self.temp(line)?;
                self.emit(op::FORMAT, d, first, (args.len() - 1) as u8, c, 0);
                return Ok(d);
            }
            "registry" => {
                let Some(Expr::Text(row)) = args.first().filter(|_| args.len() == 1) else {
                    return Err(Problem { line, text: "registry takes one text: registry(\"form/Gold Flower\")".into() });
                };
                if !row.contains('/') {
                    return Err(Problem { line, text: format!("registry(\"{row}\"): a row is named kind/name") });
                }
                let imp = self.out.import(IMPORT_REGISTRY, row, line)?;
                let d = self.temp(line)?;
                self.emit(op::REGISTRY, d, 0, 0, imp, 0);
                return Ok(d);
            }
            _ => {}
        }
        if let Some(&(function, params)) = self.fns.get(name) {
            if args.len() != params {
                return Err(Problem { line, text: format!("{name} takes {params} value{}", if params == 1 { "" } else { "s" }) });
            }
            let first = self.args(args, line)?;
            let d = self.temp(line)?;
            self.emit(op::CALL_SCRIPT, d, first, args.len() as u8, function as u16, 0);
            return Ok(d);
        }
        // The toolkit: a game function, or the plugin API as nebula.<name> (coop.<name> for co-op's calls).
        let row = if self.toolkit.rows.contains_key(name) {
            name.to_string()
        } else if let Some(choices) = self.toolkit.overloads.get(name) {
            let fitting: Vec<&String> = choices.iter().filter(|c| self.toolkit.rows[*c].0.len() == args.len()).collect();
            match fitting.as_slice() {
                [one] => (*one).clone(),
                [] => return Err(Problem { line, text: format!("{name} takes {} values", choices.iter().map(|c| self.toolkit.rows[c].0.len().to_string()).collect::<Vec<_>>().join(" or ")) }),
                _ => return Err(Problem { line, text: format!("{name} is several functions: name one ({})", choices.join(", ")) }),
            }
        } else if name.contains("::") || is_api(name) {
            return Err(Problem { line, text: format!("the game has no {name} (docs/modding/TOOLKIT.md lists every one)") });
        } else {
            return Err(Problem { line, text: format!("{name} is not a function here") });
        };
        let (params, result) = &self.toolkit.rows[&row];
        if args.len() > params.len() {
            return Err(Problem { line, text: format!("{row} takes at most {} values", params.len()) });
        }
        let gives = usize::from(!result.is_empty() && result != "a") + params.bytes().filter(u8::is_ascii_uppercase).count();
        if want > gives.max(if results.is_none() { 1 } else { 0 }) {
            return Err(Problem { line, text: format!("{row} gives {gives} value{}", if gives == 1 { "" } else { "s" }) });
        }
        let kind = if is_api(&row) { IMPORT_API } else { IMPORT_TOOLKIT };
        let imp = self.out.import(kind, &row, line)?;
        let first = self.args(args, line)?;
        let keep = if results.is_none() { gives.min(1) } else { want };
        let d = self.temps(keep.max(1), line)?;
        self.emit(op::CALL, d, first, args.len() as u8, imp, keep as u16);
        if keep == 0 && results.is_none() {
            // A call used as a value that gives nothing: none.
            let c = self.out.constant(Constant::None, line)?;
            self.emit(op::LOAD_CONST, d, 0, 0, c, 0);
        }
        Ok(d)
    }
}

/// Compiles a script's text. `name` is used in messages (its file).
/// What a handler's name answers, as the game reads it (LumaScript.cpp): its own events and the game's (the SDK's
/// events.tsv), "event:<name>" for another script's emit, "message" for every message and "message:<number>" for one
/// (an ACTMES_ name becomes its number, from the SDK's messages.tsv).
pub fn handler_name(event: &str) -> Result<String, String> {
    if let Some(name) = event.strip_prefix("event:") {
        if name.is_empty() || !name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_') {
            return Err(format!("{name} is not an event's name (letters, digits and _)"));
        }
        return Ok(event.to_string());
    }
    if let Some(message) = event.strip_prefix("message:") {
        if let Ok(number) = message.parse::<u32>() {
            return if message_names().any(|(_, n)| n == number) {
                Ok(format!("message:{number}"))
            } else {
                Err(format!("the game has no message {number} (docs/reference/lumascript.md lists them)"))
            };
        }
        return match message_names().find(|(name, _)| *name == message) {
            Some((_, number)) => Ok(format!("message:{number}")),
            None => Err(format!("the game has no message {message} (docs/reference/lumascript.md lists them)")),
        };
    }
    if event_names().any(|(name, _)| name == event) {
        return Ok(event.to_string());
    }
    Err(format!("the game has no event {event} (docs/reference/lumascript.md lists them)"))
}

/// Every handler name the game answers, and whether it is the game's event ("game": (value, name, actor), and what it
/// returns becomes the value) or an object's own ("own").
pub fn event_names() -> impl Iterator<Item = (&'static str, &'static str)> {
    include_str!("../sdk/events.tsv").lines().filter_map(|l| l.split_once('\t'))
}

/// The game's messages (ACTMES_ names) and their numbers.
pub fn message_names() -> impl Iterator<Item = (&'static str, u32)> {
    include_str!("../sdk/messages.tsv").lines().filter_map(|l| l.split_once('\t')).filter_map(|(n, v)| Some((n, v.parse().ok()?)))
}

pub fn compile(source: &str, toolkit: &Toolkit) -> Result<Vec<u8>, Problem> {
    let lexed = lex(source)?;
    let mut parser = Parser { toks: lexed.toks, at: 0 };
    let (vars, mut handlers, fns) = parser.file()?;
    for h in &mut handlers {
        h.event = handler_name(&h.event).map_err(|text| Problem { line: h.line, text })?;
    }

    let mut out = Out::default();
    let mut var_map: HashMap<String, (VarKind, u16)> = HashMap::new();
    for v in &vars {
        if var_map.contains_key(&v.name) {
            return Err(Problem { line: v.line, text: format!("{} is declared twice", v.name) });
        }
        let s = out.string(&v.name);
        let list = match v.kind {
            VarKind::Local => &mut out.locals,
            VarKind::Global => &mut out.globals,
            VarKind::Saved => &mut out.saved,
        };
        if list.len() >= u16::MAX as usize {
            return Err(Problem { line: v.line, text: "too many variables".into() });
        }
        list.push((s, v.value_kind));
        var_map.insert(v.name.clone(), (v.kind, (list.len() - 1) as u16));
    }
    let mut states: Vec<String> = Vec::new();
    for h in &handlers {
        if let Some(s) = &h.state {
            if !states.contains(s) {
                states.push(s.clone());
            }
        }
    }
    // Functions first (handlers call them by index), then handlers; a var's starting value runs before "start".
    let mut fn_map: HashMap<String, (u32, usize)> = HashMap::new();
    for (i, f) in fns.iter().enumerate() {
        if fn_map.insert(f.name.clone(), (i as u32, f.params.len())).is_some() {
            return Err(Problem { line: f.line, text: format!("fn {} is written twice", f.name) });
        }
    }
    let mut seen_handlers: Vec<(String, Option<String>)> = Vec::new();
    for h in &handlers {
        let key = (h.event.clone(), h.state.clone());
        if seen_handlers.contains(&key) {
            return Err(Problem { line: h.line, text: format!("on {} is written twice{}", h.event, h.state.as_ref().map_or(String::new(), |s| format!(" in state {s}"))) });
        }
        seen_handlers.push(key);
    }
    let inits: Vec<Stmt> = vars
        .iter()
        .filter_map(|v| v.init.clone().map(|e| Stmt::Assign(v.name.clone(), e, v.line)))
        .collect();
    let has_start = handlers.iter().any(|h| h.event == "start" && h.state.is_none());
    let start_only = HandlerDecl { event: "start".into(), state: None, params: Vec::new(), body: Vec::new(), line: 1 };
    let mut bodies: Vec<(String, Vec<String>, Vec<Stmt>, u32, bool)> = Vec::new();
    for f in &fns {
        bodies.push((f.name.clone(), f.params.clone(), f.body.clone(), f.line, false));
    }
    let mut handler_rows = Vec::new();
    let all_handlers: Vec<&HandlerDecl> = handlers.iter().chain((!has_start && !inits.is_empty()).then_some(&start_only)).collect();
    for h in &all_handlers {
        let mut params = vec!["self".to_string()];
        params.extend(h.params.iter().cloned());
        let mut body = Vec::new();
        if h.event == "start" && h.state.is_none() {
            body.extend(inits.iter().cloned());
        }
        body.extend(h.body.iter().cloned());
        let label = match &h.state {
            Some(s) => format!("{s}: on {}", h.event),
            None => format!("on {}", h.event),
        };
        handler_rows.push((h.event.clone(), h.state.clone(), bodies.len()));
        bodies.push((label, params, body, h.line, true));
    }
    for (name, params, body, line, is_handler) in &bodies {
        if params.len() > MAX_REGISTERS {
            return Err(Problem { line: *line, text: format!("{name}: too many parameters") });
        }
        let mut ctx = FnCtx {
            out: &mut out,
            toolkit,
            vars: &var_map,
            fns: &fn_map,
            states: &states,
            steps: Vec::new(),
            scopes: vec![Scope { names: Vec::new() }],
            next: 0,
            max: 0,
            is_handler: *is_handler,
            loops: Vec::new(),
            name: name.clone(),
        };
        for p in params {
            ctx.declare(p, *line)?;
        }
        ctx.block(body)?;
        let end = ctx.steps.len();
        let lands_on_end = ctx.steps.iter().any(|s| matches!(s.op, op::JUMP | op::JUMP_IF | op::JUMP_IF_NOT) && s.imm as usize == end);
        if lands_on_end || ctx.steps.last().is_none_or(|s| s.op != op::RETURN) {
            ctx.emit(op::RETURN, 0, 0, 0, 0, 0);
        }
        if ctx.steps.len() > u16::MAX as usize {
            return Err(Problem { line: *line, text: format!("{name} is too long (at most 65535 steps)") });
        }
        let registers = ctx.max.max(params.len()).max(1) as u16;
        let steps = std::mem::take(&mut ctx.steps);
        drop(ctx);
        let first = out.steps.len() as u32;
        let count = steps.len() as u32;
        out.steps.extend(steps);
        let n = out.string(name);
        out.functions.push(Function { name: n, first, count, registers, params: params.len() as u16, line: *line });
    }
    for (event, state, function) in handler_rows {
        let name = out.string(&event);
        let state = state.map_or(NO_STATE, |s| out.string(&s));
        out.handlers.push((name, function as u32, state));
    }
    let bytes = write(&out);
    if let Err(why) = verify(&bytes) {
        return Err(Problem { line: 0, text: format!("the compiler made a file the game would refuse ({why}): please report it with this script") });
    }
    Ok(bytes)
}

fn write(o: &Out) -> Vec<u8> {
    let mut b = Vec::new();
    b.extend_from_slice(b"LSC1");
    b.extend_from_slice(&FILE_VERSION.to_le_bytes());
    b.extend_from_slice(&0u16.to_le_bytes());
    for n in [o.strings.len(), o.constants.len(), o.imports.len(), o.functions.len(), o.steps.len(), o.handlers.len(), o.locals.len(), o.globals.len(), o.saved.len()] {
        b.extend_from_slice(&(n as u32).to_le_bytes());
    }
    for s in &o.strings {
        b.extend_from_slice(&(s.len() as u32).to_le_bytes());
        b.extend_from_slice(s.as_bytes());
    }
    for c in &o.constants {
        match c {
            Constant::None => b.push(KIND_NONE),
            Constant::Bool(v) => {
                b.push(KIND_BOOL);
                b.extend_from_slice(&(i64::from(*v)).to_le_bytes());
            }
            Constant::Int(v) => {
                b.push(KIND_INT);
                b.extend_from_slice(&v.to_le_bytes());
            }
            Constant::Float(bits) => {
                b.push(KIND_FLOAT);
                b.extend_from_slice(&bits.to_le_bytes());
            }
            Constant::Vec3(v) => {
                b.push(KIND_VEC3);
                for x in v {
                    b.extend_from_slice(&x.to_le_bytes());
                }
            }
            Constant::Text(s) => {
                b.push(KIND_TEXT);
                b.extend_from_slice(&s.to_le_bytes());
            }
        }
    }
    for (kind, name, line) in &o.imports {
        b.push(*kind);
        b.extend_from_slice(&name.to_le_bytes());
        b.extend_from_slice(&line.to_le_bytes());
    }
    for f in &o.functions {
        b.extend_from_slice(&f.name.to_le_bytes());
        b.extend_from_slice(&f.first.to_le_bytes());
        b.extend_from_slice(&f.count.to_le_bytes());
        b.extend_from_slice(&f.registers.to_le_bytes());
        b.extend_from_slice(&f.params.to_le_bytes());
        b.extend_from_slice(&f.line.to_le_bytes());
    }
    for s in &o.steps {
        b.extend_from_slice(&[s.op, s.dst, s.a, s.b]);
        b.extend_from_slice(&s.imm.to_le_bytes());
        b.extend_from_slice(&s.imm2.to_le_bytes());
    }
    for (name, function, state) in &o.handlers {
        b.extend_from_slice(&name.to_le_bytes());
        b.extend_from_slice(&function.to_le_bytes());
        b.extend_from_slice(&state.to_le_bytes());
    }
    for list in [&o.locals, &o.globals, &o.saved] {
        for (name, kind) in list {
            b.extend_from_slice(&name.to_le_bytes());
            b.push(*kind);
        }
    }
    b
}

/// What the game's loader checks, done here too: every count, row and operand (LumaScript.cpp load). An error names
/// what is wrong; the compiler's own output always passes (tests).
pub fn verify(bytes: &[u8]) -> Result<Summary, String> {
    struct R<'a> {
        b: &'a [u8],
        at: usize,
    }
    impl R<'_> {
        fn take(&mut self, n: usize) -> Result<&[u8], String> {
            if self.b.len() - self.at < n {
                return Err("the file ends early".into());
            }
            let s = &self.b[self.at..self.at + n];
            self.at += n;
            Ok(s)
        }
        fn u8(&mut self) -> Result<u8, String> {
            Ok(self.take(1)?[0])
        }
        fn u16(&mut self) -> Result<u16, String> {
            let s = self.take(2)?;
            Ok(u16::from_le_bytes([s[0], s[1]]))
        }
        fn u32(&mut self) -> Result<u32, String> {
            let s = self.take(4)?;
            Ok(u32::from_le_bytes([s[0], s[1], s[2], s[3]]))
        }
    }
    let mut r = R { b: bytes, at: 0 };
    if r.take(4)? != b"LSC1" {
        return Err("not a LumaScript file".into());
    }
    if r.u16()? > FILE_VERSION {
        return Err("a newer LumaScript file".into());
    }
    r.u16()?;
    let mut n = [0usize; 9];
    for x in &mut n {
        *x = r.u32()? as usize;
    }
    let [strings, constants, imports, functions, steps, handlers, locals, globals, saved] = n;
    let mut text = Vec::new();
    for _ in 0..strings {
        let len = r.u32()? as usize;
        text.push(String::from_utf8_lossy(r.take(len)?).into_owned());
    }
    let mut const_kinds = Vec::new();
    for _ in 0..constants {
        let k = r.u8()?;
        match k {
            KIND_BOOL | KIND_INT | KIND_FLOAT => {
                r.take(8)?;
            }
            KIND_VEC3 => {
                r.take(12)?;
            }
            KIND_TEXT => {
                if r.u32()? as usize >= strings {
                    return Err("a text value names no string".into());
                }
            }
            KIND_NONE => {}
            _ => return Err(format!("a value of kind {k}")),
        }
        const_kinds.push(k);
    }
    let mut import_rows = Vec::new();
    for _ in 0..imports {
        let kind = r.u8()?;
        let name = r.u32()? as usize;
        r.u32()?;
        if kind > IMPORT_EVENT || name >= strings {
            return Err("a damaged import".into());
        }
        import_rows.push((kind, text[name].clone()));
    }
    let mut fn_rows = Vec::new();
    let mut fn_names = Vec::new();
    for _ in 0..functions {
        let name = r.u32()? as usize;
        let first = r.u32()? as usize;
        let count = r.u32()? as usize;
        let regs = r.u16()? as usize;
        let params = r.u16()? as usize;
        r.u32()?;
        if regs > MAX_REGISTERS || params > regs || first > steps || count > steps - first || name >= strings {
            return Err("a damaged function row".into());
        }
        fn_rows.push((first, count, regs));
        fn_names.push((text[name].clone(), params));
    }
    let mut step_rows = Vec::new();
    for _ in 0..steps {
        let s = r.take(8)?;
        let st = Step { op: s[0], dst: s[1], a: s[2], b: s[3], imm: u16::from_le_bytes([s[4], s[5]]), imm2: u16::from_le_bytes([s[6], s[7]]) };
        if st.op >= op::COUNT {
            return Err(format!("opcode {}", st.op));
        }
        step_rows.push(st);
    }
    let mut handler_names = Vec::new();
    for _ in 0..handlers {
        let name = r.u32()? as usize;
        let function = r.u32()? as usize;
        let state = r.u32()?;
        if name >= strings || function >= functions || (state != NO_STATE && state as usize >= strings) {
            return Err("a damaged handler row".into());
        }
        handler_names.push(text[name].clone());
    }
    for _ in 0..(locals + globals + saved) {
        if r.u32()? as usize >= strings {
            return Err("a variable names no string".into());
        }
        r.u8()?;
    }
    if r.at != bytes.len() {
        return Err("bytes after the last row".into());
    }
    for (first, count, regs) in &fn_rows {
        for s in &step_rows[*first..first + count] {
            let (dst, a, b, reg) = ((s.dst as usize) < *regs, (s.a as usize) < *regs, (s.b as usize) < *regs, (s.imm as usize) < *regs);
            let range = s.a as usize + s.b as usize <= *regs;
            let imp = |kind: u8| (s.imm as usize) < imports && import_rows[s.imm as usize].0 == kind;
            let ok = match s.op {
                op::NOP => true,
                op::LOAD_CONST => dst && (s.imm as usize) < constants,
                op::MOVE | op::NEG | op::NOT | op::VEC_X | op::VEC_Y | op::VEC_Z | op::LENGTH | op::NORMALIZE | op::ABS | op::FLOOR
                | op::SQRT | op::SIN | op::COS | op::TO_INT | op::TO_FLOAT => dst && a,
                op::ADD | op::SUB | op::MUL | op::DIV | op::MOD | op::EQ | op::NE | op::LT | op::LE | op::GT | op::GE | op::AND | op::OR
                | op::DOT | op::CROSS | op::MIN | op::MAX | op::ATAN2 | op::RANDOM => dst && a && b,
                op::MAKE_VEC3 | op::LERP => dst && a && b && reg,
                op::JUMP => (s.imm as usize) < *count,
                op::JUMP_IF | op::JUMP_IF_NOT => a && (s.imm as usize) < *count,
                op::CALL => range && (imp(IMPORT_TOOLKIT) || imp(IMPORT_API)) && (s.imm2 == 0 || s.dst as usize + s.imm2 as usize <= *regs),
                op::CALL_SCRIPT => dst && range && (s.imm as usize) < functions,
                op::RETURN => s.b != 1 || a,
                op::GET_LOCAL | op::GET_GLOBAL | op::GET_SAVED => dst,
                op::SET_LOCAL | op::SET_GLOBAL | op::SET_SAVED => a,
                op::FIELD_GET => dst && a && (b || s.b == 255) && imp(IMPORT_FIELD),
                op::FIELD_SET => a && b && imp(IMPORT_FIELD),
                op::SET_STATE => (s.imm as usize) < strings,
                op::WAIT => a,
                op::EMIT => a && imp(IMPORT_EVENT),
                op::FORMAT => dst && range && (s.imm as usize) < constants && const_kinds[s.imm as usize] == KIND_TEXT,
                op::REGISTRY => dst && imp(IMPORT_REGISTRY),
                _ => false,
            };
            if !ok {
                return Err(format!("a damaged step: {} {} {} {} {} {}", op::NAMES[s.op as usize], s.dst, s.a, s.b, s.imm, s.imm2));
            }
        }
    }
    let code = fn_rows
        .iter()
        .zip(fn_names)
        .map(|(&(first, count, regs), (name, params))| FunctionCode {
            name,
            params,
            registers: regs,
            steps: step_rows[first..first + count]
                .iter()
                .map(|s| format!("{} {} {} {} {} {}", op::NAMES[s.op as usize], s.dst, s.a, s.b, s.imm, s.imm2))
                .collect(),
        })
        .collect();
    Ok(Summary { functions, steps, handlers: handler_names, imports: import_rows, code })
}

/// One function of a verified file, its steps as text (opcode dst a b imm imm2).
#[derive(Debug)]
pub struct FunctionCode {
    pub name: String,
    pub params: usize,
    pub registers: usize,
    pub steps: Vec<String>,
}

/// What a verified file holds (for `lumalink inspect` and tests).
#[derive(Debug)]
pub struct Summary {
    pub functions: usize,
    pub steps: usize,
    pub handlers: Vec<String>,
    pub imports: Vec<(u8, String)>,
    pub code: Vec<FunctionCode>,
}

/// A readable listing of a compiled script (for `lumalink inspect` and bug reports).
pub fn listing(bytes: &[u8]) -> Result<String, String> {
    let s = verify(bytes)?;
    let mut out = String::new();
    let _ = writeln!(out, "{} functions, {} steps", s.functions, s.steps);
    for h in &s.handlers {
        let _ = writeln!(out, "on {h}");
    }
    for (i, (kind, name)) in s.imports.iter().enumerate() {
        let k = ["toolkit", "api", "field", "registry", "event"][*kind as usize];
        let _ = writeln!(out, "import {i}: {k} {name}");
    }
    for f in &s.code {
        let _ = writeln!(out, "\nfn {} ({} parameters, {} registers)", f.name, f.params, f.registers);
        for (i, step) in f.steps.iter().enumerate() {
            let _ = writeln!(out, "  {i:4}  {step}");
        }
    }
    Ok(out)
}

